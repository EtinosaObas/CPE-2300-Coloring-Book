main:
    li a0, 1  #picked template 1 
    call load_template

    li t0, PRESENT
    sw zero, 0(t0) #displays the framebuffer

    li a7, 10  #exit
    ecall 



set_pixel:
    blt a0, zero, set_pixel_done #x>=0
    
    li t0, WIDTH
    bge a0, t0, set_pixel_done #x < width

    blt a1, zero, set_pixel_done # y>=0
   
    li t0, HEIGHT
    bge a1, t0, set_pixel_done # y < height

    #offset = y * width + x
    li t0, WIDTH
    mul t1, a1, t0
    add t1, t1, a0

    #address = FB + offset
    li t0, FB
    add t0, t0, t1

    sb a2, 0(t0) #store the lowest 8 bits of color
    
set_pixel_done: 
   ret
    
clear_screen:

   li t0, CLEAR
   sw a0, 0(t0)
   ret

load_template:
   addi sp, sp, -16
   sw ra, 12(sp)
   sw s0, 8(sp)
   sw s1, 4(sp)
   sw s2, 0(sp)
   
   mv s0, a0 #save template number,s0 contains the temp numb
  
   li a0, 0 
   call clear_screen 

   li a0, 0
   call clear_screen

   li t0, 1 
   beq s0, t0, template_1  #if #==1, draw flower

   j load_template_done

template_1:
   la a0, flowersketch_palette
   li a1, 4
   li a2, 16
   call setPalette

   la a0, flowersketch_runs
   la t0, flowersketch_nruns
   lw a1, 0(t0)
   li a2, 16
   call drawRLE
   
   j load_template_done

#restore the registers and return
load_template_done:
    lw s0, 8(sp)
    lw ra, 12(sp)
    addi sp, sp, 16

    ret

# setPalette(a0 = table of 0xRRGGBB words, a1 = count, a2 = first palette index)
setPalette:
    slli t0, a2, 2            # 4 bytes per palette entry
    li   t1, PAL
    add  t1, t1, t0
sp_loop:
    beqz a1, sp_done
    lw   t0, 0(a0)
    sw   t0, 0(t1)
    addi a0, a0, 4
    addi t1, t1, 4
    addi a1, a1, -1
    j    sp_loop
sp_done:
    ret

# drawRLE(a0 = runs address, a1 = number of runs, a2 = first palette index)
# FULL image: each run is 2 bytes (count 1..255, colour number); fills the screen from (0,0).
drawRLE:
    li   t0, FB               # next pixel
rle_run:
    beqz a1, rle_done
    lbu  t1, 0(a0)            # how many pixels
    lbu  t2, 1(a0)            # which colour
    add  t2, t2, a2           # -> palette index
rle_px:
    sb   t2, 0(t0)
    addi t0, t0, 1
    addi t1, t1, -1
    bnez t1, rle_px
    addi a0, a0, 2            # next run
    addi a1, a1, -1
    j    rle_run
rle_done:
    ret

# fillRect(a0 = x, a1 = y, a2 = w, a3 = h, a4 = palette index)
fillRect:
    li   t0, WIDTH
    mul  t1, a1, t0
    add  t1, t1, a0
    li   t2, FB
    add  t1, t1, t2           # top-left pixel
fr_row:
    beqz a3, fr_done
    mv   t3, t1
    mv   t4, a2
fr_px:
    sb   a4, 0(t3)
    addi t3, t3, 1
    addi t4, t4, -1
    bnez t4, fr_px
    add  t1, t1, t0           # next row
    addi a3, a3, -1
    j    fr_row
fr_done:
    ret

# drawMask(a0 = x, a1 = y, a2 = mask address, a3 = palette index)
# PARTIAL image: mask = .byte width, height, then the rows. Each row is (width+7)/8 bytes,
# bit 7 of the first byte is the leftmost pixel. 1 = paint a3, 0 = transparent (keep what is there).
drawMask:
    lbu  t0, 0(a2)            # width
    lbu  t1, 1(a2)            # height
    addi a2, a2, 2            # a2 -> first row
    addi t2, t0, 7
    srli t2, t2, 3            # bytes per row
    li   t3, 0                # row
dm_row:
    bge  t3, t1, dm_done
    li   t4, 0                # column
dm_col:
    bge  t4, t0, dm_next
    srli t5, t4, 3            # which byte of the row: column / 8
    add  t5, a2, t5
    lbu  t5, 0(t5)
    andi t6, t4, 7            # which bit: column % 8, counted from the left
    li   a4, 0x80
    srl  a4, a4, t6
    and  t5, t5, a4
    beqz t5, dm_skip          # 0 bit: transparent
    add  t5, a1, t3           # screen y = y + row
    li   t6, WIDTH
    mul  t5, t5, t6
    add  t5, t5, a0           # + x
    add  t5, t5, t4           # + column
    li   t6, FB
    add  t5, t5, t6
    sb   a3, 0(t5)
dm_skip:
    addi t4, t4, 1
    j    dm_col
dm_next:
    add  a2, a2, t2           # next mask row
    addi t3, t3, 1
    j    dm_row
dm_done:
    ret




